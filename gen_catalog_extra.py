import os, re, json
D = r"C:/Users/19409/WorkBuddy/2026-11-20-18-06-35/aigis-android/full_dump"
OUT = r"C:/Users/19409/WorkBuddy/2026-11-20-18-06-35/aigis-chs-research/catalog_generated.py"
files = sorted(n for n in os.listdir(D) if not n.endswith(".md5"))

def pick(pat):
    return [n for n in files if re.fullmatch(pat, n)]

tables = []
for n in pick(r"MessageText\d+\.atb"):
    tables.append((n, ["Message"], "mission", "各活动关卡说明(编号表)"))
for n in pick(r"QuestNameText\d+\.atb"):
    tables.append((n, ["Message"], "mission", "各活动/塔的关卡名(编号表)"))
for n in pick(r"RewardText\d+\.atb"):
    tables.append((n, ["Text"], "ui", "各活动报酬与玩法说明(编号表)"))
if "Shop2ItemV2.atb" in files:
    tables.append(("Shop2ItemV2.atb", ["ProductName"], "ui", "商店商品与礼包名称"))
if "SpecialEffectsType.atb" in files:
    tables.append(("SpecialEffectsType.atb", ["Name", "Effect", "Target"], "gameplay", "战神加护等特殊效果名称/效果/对象"))

archives = [(n, ["Message", "Name"], "战斗剧情对话") for n in pick(r"BattleTalkEvent\d+\.aar")]

with open(OUT, "w", encoding="utf-8") as fp:
    fp.write('"""Auto-generated by gen_catalog_extra.py — DO NOT EDIT BY HAND.\n\n')
    fp.write("Numbered per-event tables and the in-battle dialogue archives that the base\n")
    fp.write("catalog never covered. Regenerate whenever the game adds new quest ids.\n")
    fp.write('"""\n\n')
    fp.write("EXTRA_TABLES = [\n")
    for n, cols, cat, desc in tables:
        fp.write(f'    ({n!r}, {cols!r}, {cat!r}, {desc!r}),\n')
    fp.write("]\n\nEXTRA_ARCHIVES = [\n")
    for n, cols, desc in archives:
        fp.write(f'    ({n!r}, {cols!r}, {desc!r}),\n')
    fp.write("]\n")
print(f"tables={len(tables)} archives={len(archives)} -> {OUT}")
