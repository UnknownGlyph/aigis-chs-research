applied = 0
for jp, zh in POLISH.items():
    if jp in aod_clean:
        ob = aod_clean[jp]["bytes"]
        zb = len(zh.encode("utf-8"))
        if zb <= ob:
            alod[jp] = zh
            applied += 1
        else:
            print(f"SKIP {jp!r} -> {zh!r}: {zb} > {ob}")

# Also fix any stray "素材" kanji -> SC "素材", and check no Hangul or kana left in alod values!
REAL_KANA = re.compile(r"[\u3041-\u3096\u30a1-\u30f6\u30fd-\u30ff]")
HANGUL = re.compile(r"[\uAC00-\uD7AF]")
rem_kana = []
rem_hangul = []
for k, v in list(alod.items()):
    v = v.replace("聖霊", "圣灵").replace("預り所", "存放处").replace("預かり所", "存放处").replace("かーりー", "卡莉")
    if len(v.encode("utf-8")) <= aod_clean[k]["bytes"]:
        alod[k] = v
    if REAL_KANA.search(alod[k]):
        rem_kana.append((k, alod[k]))
    if HANGUL.search(alod[k]):
        rem_hangul.append((k, alod[k]))

